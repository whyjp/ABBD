package knowledge

import (
	"fmt"
	"strings"

	"github.com/whyjp/abbd/internal/model"
	"github.com/whyjp/abbd/internal/ssot"
)

// BlueprintFile is the one page an agent reads first: the current blueprint, nothing historical.
const BlueprintFile = "BLUEPRINT.md"

// HistoryDirs hold per-request records (receipts, request texts, decision log, run evidence,
// derived views). They are the audit trail, not the blueprint; reading them as context mixes
// superseded intent into the current one. Search tools skip them via .abbd/.ignore and the
// plugin's PreToolUse hook refuses direct reads.
var HistoryDirs = []string{"changes", "requirements", "decisions", "verification", "generated"}

var historyFiles = []string{"candidates.yaml", "state.yaml", "learning.yaml", "bootstrap-report.md", "bootstrap-report.yaml"}

// writeIgnore keeps history out of ripgrep-based search (Claude Code Grep, Codex, most editors).
func writeIgnore(root string) error {
	var b strings.Builder
	b.WriteString("# abbd: history is the audit trail, not context. Read BLUEPRINT.md or use `abbd inspect`.\n")
	for _, d := range HistoryDirs {
		b.WriteString(d + "/\n")
	}
	for _, f := range historyFiles {
		b.WriteString(f + "\n")
	}
	return ssot.WriteText(root, ".ignore", b.String())
}

// StandingRules are project-scope requirements still in force, newest last.
func StandingRules(s *ssot.Snapshot) []*model.Requirement {
	var out []*model.Requirement
	for _, id := range model.SortedKeys(s.Requirements) {
		r := s.Requirements[id]
		if r.Scope == model.ScopeProject && r.Statement.Confirmation != model.Rejected {
			out = append(out, r)
		}
	}
	return out
}

// renderBlueprint is the current state only: rules, modules, contracts, features, open
// decisions. It is regenerated on every publish, so it never carries superseded text.
func renderBlueprint(s *ssot.Snapshot) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Blueprint · %s\n\n", s.Project.Name)
	b.WriteString("Current state of the project's blueprint, generated by abbd. Read this before changing code.\n")
	b.WriteString("History (.abbd/changes, requirements, decisions, verification, generated) is the audit trail, not context.\n")
	b.WriteString("Details: `abbd inspect ID`, `abbd contracts list`, `abbd decisions`.\n\n")

	b.WriteString("## Standing rules (apply to every path, including new ones)\n\n")
	rules := StandingRules(s)
	if len(rules) == 0 {
		b.WriteString("- none recorded\n")
	}
	for _, r := range rules {
		fmt.Fprintf(&b, "- %s: %s (%s)\n", r.ID, r.Statement.Value, r.Statement.Origin)
	}

	b.WriteString("\n## Modules\n\n")
	for _, id := range model.SortedKeys(s.Modules) {
		m := s.Modules[id]
		if m.Status == model.ItemRemoved {
			continue
		}
		fmt.Fprintf(&b, "- %s `%s` %s [%s]", id, m.Path, m.Responsibility.Value, m.Responsibility.Badge())
		if len(m.DependsOn) > 0 {
			fmt.Fprintf(&b, " · depends on %s", strings.Join(m.DependsOn, ", "))
		}
		if len(m.DependencyPolicy.Forbidden) > 0 {
			fmt.Fprintf(&b, " · must not depend on %s", strings.Join(m.DependencyPolicy.Forbidden, ", "))
		}
		b.WriteString("\n")
	}

	b.WriteString("\n## External contracts\n\n")
	for _, id := range model.SortedKeys(s.Modules) {
		for _, c := range s.Modules[id].ExternalContracts {
			if c.Status == model.ItemRemoved {
				continue
			}
			consumers := "consumers ?"
			if c.ExternalConsumers != nil {
				consumers = fmt.Sprintf("external consumers %v", *c.ExternalConsumers)
			}
			fmt.Fprintf(&b, "- %s %s %s `%s` (owner %s) · %s · %s\n", c.ID, c.Kind, c.Direction, c.Selector, id, c.Compatibility.Value, consumers)
		}
	}

	b.WriteString("\n## Features\n\n")
	for _, id := range model.SortedKeys(s.Features) {
		f := s.Features[id]
		if f.Status == model.ItemRemoved {
			continue
		}
		fmt.Fprintf(&b, "- %s %s: %s [%s]", id, f.Name, f.Intent.Purpose.Value, f.Intent.Purpose.Badge())
		if len(f.EntryPoints) > 0 {
			var eps []string
			for _, e := range f.EntryPoints {
				eps = append(eps, e.Selector)
			}
			fmt.Fprintf(&b, " · entry %s", strings.Join(eps, ", "))
		}
		b.WriteString("\n")
		for _, inv := range f.Intent.Invariants {
			fmt.Fprintf(&b, "  - invariant: %s (%s, %s)\n", inv.Claim, inv.Origin, inv.Verification)
		}
	}

	b.WriteString("\n## Open decisions\n\n")
	open := 0
	for _, id := range model.SortedKeys(s.Decisions) {
		d := s.Decisions[id]
		if d.Confirmation == model.Unconfirmed {
			fmt.Fprintf(&b, "- %s %s → %s (default, unconfirmed)\n", id, d.Question, d.Chosen)
			open++
		}
	}
	if open == 0 {
		b.WriteString("- none\n")
	}
	return b.String()
}

func writeBlueprint(s *ssot.Snapshot) error {
	if err := writeIgnore(s.Root); err != nil {
		return err
	}
	return ssot.WriteText(s.Root, BlueprintFile, renderBlueprint(s))
}
