package main

import "testing"

func TestADraftIsTheFirstSentenceOfTheCommentThatDocumentsTheSymbol(t *testing.T) {
	goSrc := "// Copyright 2024 The Authors. Licensed MIT.\n\n// Package billing charges cards. It retries twice.\npackage billing\n\nfunc use() { scope() }\n\n// scope declares what a task touches. More here.\nfunc (e env) scope(list string) error { return nil }\n"
	for _, c := range []struct {
		name, text, symbol string
		md                 bool
		want               string
	}{
		{"declaration over first use", goSrc, "scope", false, "scope declares what a task touches."},
		{"header past the licence", goSrc, "", false, "Package billing charges cards."},
		{"no header, only a comment in a body", "package x\n\nfunc f() {\n\t// TODO: remove this hack\n}\n", "", false, ""},
		{"generated header", "// Code generated by protoc. DO NOT EDIT.\n\npackage pb\n", "", false, ""},
		{"python header", "#!/usr/bin/env python\n# Loads the config.\nimport os\n", "", false, "Loads the config."},
		{"python docstring below", "def load():\n    \"\"\"Loads the config.\n\n    More.\n    \"\"\"\n    pass\n\n# helper for tests\n", "load", false, "Loads the config."},
		{"one-line docstring", "def load():\n    \"\"\"Loads the config.\"\"\"\n", "load", false, "Loads the config."},
		{"rust doc past an attribute", "/// A parsed line.\n#[derive(Debug)]\npub struct Line {}\n", "Line", false, "A parsed line."},
		{"ts doc past a decorator", "/** Serves users. */\n@Injectable()\nexport class UserService {}\n", "UserService", false, "Serves users."},
		{"c block comment", "/*\n * Parses input\n * line by line.\n */\nint parse(char *s) {\n", "parse", false, "Parses input line by line."},
		{"c preprocessor is code", "#define MAX 3\n#ifndef X\nint main(void) {\n", "", false, ""},
		{"c pointer line is code", "int f(int *p) {\n*p = 1;\n}\n", "", false, ""},
		{"java method", "class A {\n  // Runs the job once.\n  public void run() {\n  }\n  // calls run later\n  void x() { run(); }\n}\n", "run", false, "Runs the job once."},
		{"a call is no declaration", "// calls run later\nvoid x() { run(); }\n", "run", false, ""},
		{"no comment", "func scope() {}\n", "scope", false, ""},
		{"abbreviation", "// Opens a file, e.g. a log. Then more.\nfunc open() {}\n", "open", false, "Opens a file, e.g. a log."},
		{"licence word in prose", "// Package license checks SPDX expressions.\npackage license\n", "", false, "Package license checks SPDX expressions."},
		{"markdown", "---\nname: x\n---\n# Title\n\n[![CI](https://x/badge.svg)](https://x)\n\n```sh\nnpm i foo\n```\n\nThe skill reads the blueprint. Then more.\n", "", true, "The skill reads the blueprint."},
	} {
		if got := firstSentence(docComment(c.text, c.symbol, c.md)); got != c.want {
			t.Errorf("%s: drafted %q, want %q", c.name, got, c.want)
		}
	}
}
