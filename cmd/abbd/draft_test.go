package main

import "testing"

// A draft comes from the doc comment Go attaches to a declaration, never
// from a comment above a call, and with no symbol from the file's header.
func TestADraftComesFromAGoDocCommentOrTheFileHeader(t *testing.T) {
	goSrc := "// Copyright 2024 The Authors. Licensed MIT.\n\n// Package billing charges cards. It retries twice.\npackage billing\n\nfunc a() int {\n\t// retry once more\n\treturn scope(1)\n}\n\nfunc b() {\n\t// clean up\n\tdefer close(f)\n\t// guard\n\tif ok(x) {\n\t}\n}\n\n// scope declares what a task touches. More here.\nfunc (e env) scope(list string) error { return nil }\n\nfunc close(f int) {}\n\ntype (\n\t// Line is one parsed line.\n\tLine struct{}\n)\n"
	for _, c := range []struct{ name, symbol, want string }{
		{"method doc past a call above a return", "scope", "scope declares what a task touches."},
		{"no doc, though a call above it has a comment", "close", ""},
		{"a name that is only called", "ok", ""},
		{"type in a group", "Line", "Line is one parsed line."},
	} {
		if got := firstSentence(goSymbolDoc(goSrc, c.symbol)); got != c.want {
			t.Errorf("%s: drafted %q, want %q", c.name, got, c.want)
		}
	}
	for _, c := range []struct {
		name, text string
		goFile     bool
		want       string
	}{
		{"go package doc past the licence", goSrc, true, "Package billing charges cards."},
		{"go file with only a comment in a body", "package x\n\nfunc f() {\n\t// TODO: remove this hack\n}\n", true, ""},
		{"go generated file", "// Code generated by protoc. DO NOT EDIT.\n\npackage pb\n", true, ""},
		{"go generated mark on the package clause", "// Code generated by protoc. DO NOT EDIT.\npackage pb\n", true, ""},
		{"python header", "#!/usr/bin/env python\n# Loads the config.\nimport os\n", false, "Loads the config."},
		{"python module docstring past a coding line", "# -*- coding: utf-8 -*-\n\"\"\"Loads config.\n\nMore.\n\"\"\"\nimport os\n", false, "Loads config."},
		{"python comment above a call is no header", "def a():\n    # fallback\n    return load()\n", false, ""},
		{"c block header", "/*\n * Parses input\n * line by line.\n */\n#include <stdio.h>\n", false, "Parses input line by line."},
		{"c preprocessor is code", "#define MAX 3\n#ifndef X\n/* late */\n", false, ""},
		{"rust inner doc", "//! Reads the buffer. Then more.\nuse std::io;\n", false, "Reads the buffer."},
		{"abbreviation", "// Opens a file, e.g. a log. Then more.\nint x;\n", false, "Opens a file, e.g. a log."},
		{"licence word in prose", "// license checks SPDX expressions.\nint x;\n", false, "license checks SPDX expressions."},
	} {
		if got := firstSentence(header(c.text, c.goFile)); got != c.want {
			t.Errorf("%s: drafted %q, want %q", c.name, got, c.want)
		}
	}
}
